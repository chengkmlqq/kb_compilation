def main() -> None:
    db = get_sessionmaker()()
    created = updated = 0
    try:
        # 固定分类（通用/摘要）：缺失时创建，已存在仅补 descr/合并 cat_type
        for category, label, descr, cat_type, sort_num in FIXED_CATEGORIES:
            row = db.execute(
                select(TapeCategory).where(TapeCategory.category == category)
            ).scalars().first()
            if row is None:
                db.add(
                    TapeCategory(
                        id=uuid.uuid4().hex,
                        category=category,
                        label=label,
                        descr=descr,
                        cat_type=cat_type,
                        sort_num=sort_num,
                        state="1",
                    )
                )
                created += 1
            else:
                if row.cat_type not in (cat_type, "both"):
                    row.cat_type = "both"  # 类型不一致合并，避免树里看不到
                    updated += 1
                if not row.descr and descr:
                    row.descr = descr  # 空白不覆盖，仅补填
                    updated += 1
        db.commit()

        # 一级领域
        for i, (domain, _rows) in enumerate(CATEGORY_TREE):
            row = db.execute(
                select(TapeCategory).where(TapeCategory.category == domain)
            ).scalars().first()
            if row is None:
                db.add(
                    TapeCategory(
                        id=uuid.uuid4().hex,
                        category=domain,
                        label=domain,
                        descr=DOMAIN_DESCR.get(domain),
                        cat_type='tape',
                        sort_num=1000 + i,  # 领域排通用/摘要之后（通用 1、摘要 2）
                        state='1',
                    )
                )
                created += 1
            else:
                if row.cat_type not in ('tape', 'both'):
                    row.cat_type = 'both'
                    updated += 1
                if not row.descr and DOMAIN_DESCR.get(domain):
                    row.descr = DOMAIN_DESCR[domain]  # 空白不覆盖，仅补填
                    updated += 1
        db.commit()

        # 二级文档类型（挂在领域下）；清单内跨领域同名文档类型只挂首个领域
        planned: set[str] = set()
        skipped_dup: list[str] = []
        for i, (domain, rows) in enumerate(CATEGORY_TREE):
            for j, (doc, descr) in enumerate(rows):
                if doc in planned:
                    skipped_dup.append(f"{doc}(@{domain})")
                    continue  # 已在清单前段计划插入（跨领域重名，如 经营指标/风险管理/知识产权）
                row = db.execute(
                    select(TapeCategory).where(TapeCategory.category == doc)
                ).scalars().first()
                if row is None:
                    planned.add(doc)
                    db.add(
                        TapeCategory(
                            id=uuid.uuid4().hex,
                            category=doc,
                            label=doc,
                            descr=descr,
                            parent_id=domain,
                            cat_type='tape',
                            sort_num=2000 + i * 100 + j,
                            state='1',
                        )
                    )
                    created += 1
                else:
                    planned.add(doc)
                    if not row.parent_id:
                        # 已存在但未挂父级（如用户手工建的）→ 补挂到领域
                        row.parent_id = domain
                        updated += 1
                    if not row.descr and descr:
                        row.descr = descr  # 空白不覆盖，仅补填
                        updated += 1
        db.commit()
        dup_note = f"；跳过跨领域重名 {len(skipped_dup)} 项：{', '.join(skipped_dup)}" if skipped_dup else ""
        print(f'[seed_tape_categories] OK: 新建 {created} / 修正 {updated} 条{dup_note}')
    finally:
        db.close()


if __name__ == "__main__":
    main()
