def parse_spec_name(file_name):
    """从文件名解析 (规范体系, 分册, 版本)。

    例：
      中国移动省级NG2-BASS(v5.0)技术规范总册.docx
        → ('中国移动省级NG2-BASS技术规范', '总册', 'v5.0')
      中国移动省级NG2-BASS(v4.5)技术规范逻辑模型分册.docx
        → ('中国移动省级NG2-BASS技术规范', '逻辑模型分册', 'v4.5')
      附录一：中国移动省级NG2-BASS(v5.0)技术规范核心元模型规范.docx
        → ('中国移动省级NG2-BASS技术规范', '附录一：核心元模型规范', 'v5.0')
      中国移动企业级省大数据平台技术规范数据模型分册-已修订.docx
        → ('中国移动企业级省大数据平台技术规范', '数据模型分册', '已修订')
    """
    name = re.sub(r'\.(docx|doc|pdf|xlsx|xls)$', '', file_name or '', flags=re.I).strip()
    version = ''
    m = re.search(r'[（(]\s*[vV](\d+(?:\.\d+)*)\s*[)）]', name)
    if m:
        version = 'v' + m.group(1)
        name = name[:m.start()] + name[m.end():]
    if re.search(r'[-—－]已修订$', name) or name.endswith('（已修订）'):
        version = version or '已修订'
        name = re.sub(r'[-—－]已修订$', '', name).replace('（已修订）', '')
    appendix = ''
    m = re.match(r'^(附录[一二三四五六七八九十\d]*)\s*[：:]\s*', name)
    if m:
        appendix = m.group(1)
        name = name[m.end():]
    system, rest = '', ''
    for pref in SYSTEM_PREFIXES:
        if name.startswith(pref):
            system, rest = pref, name[len(pref):]
            break
    if not system:
        m = re.search(r'技术规范', name)
        if m:
            system, rest = name[:m.end()], name[m.end():]
        else:
            system, rest = name, ''
    volume = f'{appendix}：{rest}' if appendix else rest
    volume = volume.strip('：: 　') or rest.strip()
    if appendix and not rest:
        volume = appendix
    return system.strip(), volume.strip(), version


